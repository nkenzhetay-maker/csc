-- CSC Global — ilaç talep takibi (firmalar, talepler, talep kalemleri, form dosyaları)
-- Tamamı YALNIZCA admin içindir: ziyaretçi (anon) hiçbir satırı göremez veya yazamaz.

create table if not exists public.firmalar (
  id              bigint generated by default as identity primary key,
  unvan           text not null check (char_length(unvan) between 1 and 300),
  ulke            text not null default '' check (char_length(ulke) <= 100),
  adres           text not null default '' check (char_length(adres) <= 600),
  vergi_no        text not null default '' check (char_length(vergi_no) <= 60),
  vergi_dairesi   text not null default '' check (char_length(vergi_dairesi) <= 120),
  ruhsat_no       text not null default '' check (char_length(ruhsat_no) <= 120),
  faaliyet_alani  text not null default '' check (char_length(faaliyet_alani) <= 120),
  telefon         text not null default '' check (char_length(telefon) <= 60),
  email           text not null default '' check (char_length(email) <= 200),
  web             text not null default '' check (char_length(web) <= 300),
  yetkili_ad      text not null default '' check (char_length(yetkili_ad) <= 200),
  yetkili_unvan   text not null default '' check (char_length(yetkili_unvan) <= 200),
  yetkili_telefon text not null default '' check (char_length(yetkili_telefon) <= 60),
  yetkili_email   text not null default '' check (char_length(yetkili_email) <= 200),
  kara_liste      boolean not null default false,
  kara_liste_nedeni text not null default '' check (char_length(kara_liste_nedeni) <= 1000),
  notlar          text not null default '' check (char_length(notlar) <= 4000),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create table if not exists public.talepler (
  id            bigint generated by default as identity primary key,
  firma_id      bigint not null references public.firmalar(id) on delete cascade,
  form_no       text not null default '' check (char_length(form_no) <= 60),
  talep_tarihi  date not null default current_date,
  kaynak        text not null default 'Form' check (kaynak in ('Form', 'E-posta', 'WhatsApp', 'Telefon', 'Diğer')),
  durum         text not null default 'yeni'
                check (durum in ('yeni', 'fiyat_calisiliyor', 'teklif_verildi', 'pazarlik', 'siparis', 'kaybedildi', 'yanit_yok')),
  teklif_tarihi date,
  teklif_tutari numeric(14,2) check (teklif_tutari is null or teklif_tutari >= 0),
  para_birimi   text not null default 'USD' check (para_birimi in ('USD', 'EUR', 'TRY', 'RUB', 'KZT', 'AZN')),
  teslim_sekli  text not null default '' check (char_length(teslim_sekli) <= 120),
  odeme_sekli   text not null default '' check (char_length(odeme_sekli) <= 200),
  termin        text not null default '' check (char_length(termin) <= 120),
  soguk_zincir  boolean,
  ek_notlar     text not null default '' check (char_length(ek_notlar) <= 4000),
  ic_notlar     text not null default '' check (char_length(ic_notlar) <= 4000),
  dosya_yolu    text check (dosya_yolu is null or char_length(dosya_yolu) <= 400),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists talepler_firma_idx on public.talepler (firma_id);
create index if not exists talepler_tarih_idx on public.talepler (talep_tarihi desc);

create table if not exists public.talep_kalemleri (
  id           bigint generated by default as identity primary key,
  talep_id     bigint not null references public.talepler(id) on delete cascade,
  sira         integer not null default 0,
  ilac_id      bigint references public.ilaclar(id) on delete set null,
  urun_adi     text not null check (char_length(urun_adi) between 1 and 300),
  etkin_madde  text not null default '' check (char_length(etkin_madde) <= 300),
  form_doz     text not null default '' check (char_length(form_doz) <= 200),
  miktar       text not null default '' check (char_length(miktar) <= 60),
  ihrac_ulkesi text not null default '' check (char_length(ihrac_ulkesi) <= 100),
  aciklama     text not null default '' check (char_length(aciklama) <= 1000),
  birim_fiyat  numeric(14,2) check (birim_fiyat is null or birim_fiyat >= 0)
);
create index if not exists talep_kalemleri_talep_idx on public.talep_kalemleri (talep_id);

drop trigger if exists firmalar_updated_at on public.firmalar;
create trigger firmalar_updated_at before update on public.firmalar for each row execute function public.set_updated_at();
drop trigger if exists talepler_updated_at on public.talepler;
create trigger talepler_updated_at before update on public.talepler for each row execute function public.set_updated_at();

alter table public.firmalar enable row level security;
alter table public.talepler enable row level security;
alter table public.talep_kalemleri enable row level security;
revoke all on public.firmalar, public.talepler, public.talep_kalemleri from anon;

drop policy if exists "firmalar yalnızca admin" on public.firmalar;
create policy "firmalar yalnızca admin" on public.firmalar for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "talepler yalnızca admin" on public.talepler;
create policy "talepler yalnızca admin" on public.talepler for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "talep kalemleri yalnızca admin" on public.talep_kalemleri;
create policy "talep kalemleri yalnızca admin" on public.talep_kalemleri for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- Doldurulmuş form dosyaları (kaşeli/imzalı PDF, Word, fotoğraf): gizli depo, yalnızca admin.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('talep-formlari', 'talep-formlari', false, 15728640,
        array['application/pdf', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
              'application/msword', 'image/jpeg', 'image/png', 'image/webp', 'image/heic'])
on conflict (id) do nothing;

drop policy if exists "talep formları admin okur" on storage.objects;
create policy "talep formları admin okur" on storage.objects for select to authenticated
  using (bucket_id = 'talep-formlari' and (select public.is_admin()));
drop policy if exists "talep formları admin yükler" on storage.objects;
create policy "talep formları admin yükler" on storage.objects for insert to authenticated
  with check (bucket_id = 'talep-formlari' and (select public.is_admin()));
drop policy if exists "talep formları admin siler" on storage.objects;
create policy "talep formları admin siler" on storage.objects for delete to authenticated
  using (bucket_id = 'talep-formlari' and (select public.is_admin()));
